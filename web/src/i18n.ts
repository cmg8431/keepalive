export const dicts = { ko, en };

export function initialLang(): Lang {
  const saved = localStorage.getItem("keepalive-lang");
  if (saved === "ko" || saved === "en") return saved;
  return navigator.language.startsWith("ko") ? "ko" : "en";
}
